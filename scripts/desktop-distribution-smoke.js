'use strict'

const fs = require('fs')
const path = require('path')
const os = require('os')
const assert = require('assert')
const { entryName, inventory, builderConfig, publish, writeReport, checksums, assertHeader, squashfsRange } = require('./desktop-distribution')
const { allowsDirectoryTakeover } = require('../shell/installer')
const { prune } = require('./release-retention')
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-distribution-'))
try {
  assert.strictEqual(entryName('win-x64'), 'Agent.exe')
  const windows = builderConfig('win-x64', temporary)
  assert.strictEqual(windows.nsis.oneClick, false, 'Windows uses the assisted installer')
  assert.strictEqual(windows.nsis.allowToChangeInstallationDirectory, true, 'users can select the installation directory')
  assert.strictEqual(windows.nsis.deleteAppDataOnUninstall, false, 'installation changes preserve user data')
  assert.strictEqual(entryName('linux-arm64'), 'Agent.AppImage')
  assert.strictEqual(entryName('mac-x64'), 'Agent.app')
  const app = path.join(temporary, 'app')
  fs.mkdirSync(app)
  assert(allowsDirectoryTakeover(app, 'linux', {}), 'legacy directories remain compatible')
  assert(!allowsDirectoryTakeover(app, 'linux', { APPIMAGE: '/tmp/Agent.AppImage' }), 'read-only AppImage mounts never enter directory replacement')
  for (const kind of ['nsis', 'appimage', 'unknown']) {
    fs.writeFileSync(path.join(app, 'distribution.json'), JSON.stringify({ formatVersion: 1, kind, directoryTakeover: false }))
    assert(!allowsDirectoryTakeover(app, 'win32', {}))
  }
  fs.writeFileSync(path.join(app, 'distribution.json'), JSON.stringify({ formatVersion: 1, kind: 'app-bundle', directoryTakeover: true }))
  assert(allowsDirectoryTakeover(app, 'darwin', {}))
  fs.writeFileSync(path.join(app, 'distribution.json'), '{')
  assert(!allowsDirectoryTakeover(app, 'win32', {}), 'corrupted managed marker fails closed')
  const reports = path.join(temporary, 'reports')
  fs.mkdirSync(reports)
  fs.writeFileSync(path.join(reports, 'mac-arm64.json'), '{"build":"previous"}\n')
  writeReport({ target: 'mac-arm64', report: { build: 'candidate' } }, true, reports)
  assert.strictEqual(JSON.parse(fs.readFileSync(path.join(reports, 'mac-arm64.json'))).build, 'previous', 'staging preserves the actual delivery audit')
  assert.strictEqual(JSON.parse(fs.readFileSync(path.join(reports, 'mac-arm64.staged.json'))).build, 'candidate')
  writeReport({ target: 'mac-arm64', report: { build: 'published' } }, false, reports)
  assert.strictEqual(JSON.parse(fs.readFileSync(path.join(reports, 'mac-arm64.json'))).build, 'published')
  const work = path.join(temporary, 'work'), output = path.join(temporary, 'desktop')
  fs.mkdirSync(work); fs.mkdirSync(output)
  const old = path.join(output, 'Agent-linux-arm64')
  fs.mkdirSync(old); fs.writeFileSync(path.join(old, 'Agent.AppImage'), 'old-valid')
  assert.throws(() => publish({ target: 'linux-arm64', staged: path.join(work, 'missing') }, output))
  assert.strictEqual(fs.readFileSync(path.join(old, 'Agent.AppImage'), 'utf8'), 'old-valid', 'publish failure restores the previous delivery')
  const staged = path.join(work, 'delivery')
  fs.mkdirSync(staged); fs.writeFileSync(path.join(staged, 'Agent.AppImage'), 'new-valid')
  publish({ target: 'linux-arm64', staged }, output)
  assert.deepStrictEqual(fs.readdirSync(old), ['Agent.AppImage'])
  assert.strictEqual(fs.readFileSync(path.join(old, 'Agent.AppImage'), 'utf8'), 'new-valid')
  const payloadBeforeFinder = inventory(old)
  fs.writeFileSync(path.join(old, '.DS_Store'), 'Finder metadata')
  assert.deepStrictEqual(inventory(old), payloadBeforeFinder, 'Finder metadata cannot invalidate a published application')
  checksums(output)
  const before = fs.readFileSync(path.join(output, 'SHA256SUMS.txt'), 'utf8')
  assert(before.includes('Agent-linux-arm64/Agent.AppImage'))
  assert(!before.includes('.DS_Store'), 'checksums exclude volatile Finder metadata')
  prune(output)
  assert.strictEqual(fs.readFileSync(path.join(output, 'SHA256SUMS.txt'), 'utf8'), before, 'cleanup preserves new-format checksum entries')
  assert.strictEqual(inventory(old).length, 1)
  const elf = Buffer.alloc(4096)
  elf.write('7f454c46', 0, 'hex'); elf[4] = 2; elf.writeUInt16LE(183, 18)
  const binary = path.join(temporary, 'elf'); fs.writeFileSync(binary, elf)
  assertHeader(binary, 'linux-arm64')
  assert.throws(() => assertHeader(binary, 'linux-x64'), /INVALID_ELF_ARCH/)
  assert.throws(() => assertHeader(binary, 'win-x64'), /INVALID_PE/)
  const image = Buffer.alloc(300)
  image.write('hsqs', 4) // Runtime may contain the magic as a string constant.
  image.write('hsqs', 100); image.writeUInt16LE(4, 128); image.writeBigUInt64LE(BigInt(150), 140)
  assert.deepStrictEqual(squashfsRange(image), { offset: 100, size: 150 })
  image.writeBigUInt64LE(BigInt(500), 140)
  assert.throws(() => squashfsRange(image), /APPIMAGE_SQUASHFS_MISSING/)
  console.log('desktop distribution: managed startup, single-entry delivery, failed publish rollback, cleanup/checksums, architecture passed')
} finally { fs.rmSync(temporary, { recursive: true, force: true }) }
